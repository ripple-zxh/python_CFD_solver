import numpy as np
import matplotlib.pyplot as plt

# -----------------------------
# 基本参数
# -----------------------------
Lx = 50.0        # x方向长度，单位 m
Ly = 50.0        # y方向长度，单位 m

nx, ny = 50, 50  # 网格数量
dx = Lx / (nx - 1)
dy = Ly / (ny - 1)

second = 100     # 时间步数，不是真正的100秒
dt = 0.1         # 时间步长，建议别直接用1，容易不稳定

rho = 1000.0     # 密度，水约为1000 kg/m^3
miu = 0.001      # 动力粘度，水约为0.001 Pa·s
nu = miu / rho   # 运动粘度，速度方程里用这个

pressure_iter = 30  # 每一步压力泊松方程迭代次数

# -----------------------------
# 初始化速度和压力
# -----------------------------
u = np.zeros((nx, ny))  # x方向速度
v = np.zeros((nx, ny))  # y方向速度
p = np.zeros((nx, ny))  # 压力

# -----------------------------
# 主循环
# -----------------------------
for n in range(second):

    # 保存上一步速度
    un = u.copy()
    vn = v.copy()

    # -----------------------------
    # 构造压力泊松方程右端项 b
    # 作用：让速度场尽量满足不可压缩条件 div(u)=0
    # -----------------------------
    b = np.zeros_like(p)

    u_x = (un[2:, 1:-1] - un[:-2, 1:-1]) / (2 * dx)
    u_y = (un[1:-1, 2:] - un[1:-1, :-2]) / (2 * dy)

    v_x = (vn[2:, 1:-1] - vn[:-2, 1:-1]) / (2 * dx)
    v_y = (vn[1:-1, 2:] - vn[1:-1, :-2]) / (2 * dy)

    b[1:-1, 1:-1] = rho * (
        (u_x + v_y) / dt
        - u_x**2
        - 2 * u_y * v_x
        - v_y**2
    )

    # -----------------------------
    # 压力泊松方程迭代
    # ∇²p = b
    # -----------------------------
    for it in range(pressure_iter):
        pn = p.copy()

        p[1:-1, 1:-1] = (
            (pn[2:, 1:-1] + pn[:-2, 1:-1]) * dy**2
            + (pn[1:-1, 2:] + pn[1:-1, :-2]) * dx**2
            - b[1:-1, 1:-1] * dx**2 * dy**2
        ) / (2 * (dx**2 + dy**2))

        # 压力边界条件：零法向梯度
        p[0, :] = p[1, :]
        p[-1, :] = p[-2, :]
        p[:, 0] = p[:, 1]
        p[:, -1] = p[:, -2]

    # -----------------------------
    # 计算一阶导数
    # -----------------------------
    u_x = (un[2:, 1:-1] - un[:-2, 1:-1]) / (2 * dx)
    u_y = (un[1:-1, 2:] - un[1:-1, :-2]) / (2 * dy)

    v_x = (vn[2:, 1:-1] - vn[:-2, 1:-1]) / (2 * dx)
    v_y = (vn[1:-1, 2:] - vn[1:-1, :-2]) / (2 * dy)

    # -----------------------------
    # 计算二阶导数
    # -----------------------------
    u_xx = (un[2:, 1:-1] - 2 * un[1:-1, 1:-1] + un[:-2, 1:-1]) / dx**2
    u_yy = (un[1:-1, 2:] - 2 * un[1:-1, 1:-1] + un[1:-1, :-2]) / dy**2

    v_xx = (vn[2:, 1:-1] - 2 * vn[1:-1, 1:-1] + vn[:-2, 1:-1]) / dx**2
    v_yy = (vn[1:-1, 2:] - 2 * vn[1:-1, 1:-1] + vn[1:-1, :-2]) / dy**2

    # -----------------------------
    # 计算压力梯度
    # -----------------------------
    p_x = (p[2:, 1:-1] - p[:-2, 1:-1]) / (2 * dx)
    p_y = (p[1:-1, 2:] - p[1:-1, :-2]) / (2 * dy)

    # -----------------------------
    # 更新 u 速度
    # u_t = -u*u_x - v*u_y - p_x/rho + nu*(u_xx + u_yy)
    # -----------------------------
    u[1:-1, 1:-1] = un[1:-1, 1:-1] + dt * (
        - un[1:-1, 1:-1] * u_x
        - vn[1:-1, 1:-1] * u_y
        - p_x / rho
        + nu * (u_xx + u_yy)
    )

    # -----------------------------
    # 更新 v 速度
    # v_t = -u*v_x - v*v_y - p_y/rho + nu*(v_xx + v_yy)
    # -----------------------------
    v[1:-1, 1:-1] = vn[1:-1, 1:-1] + dt * (
        - un[1:-1, 1:-1] * v_x
        - vn[1:-1, 1:-1] * v_y
        - p_y / rho
        + nu * (v_xx + v_yy)
    )

    # -----------------------------
    # 速度边界条件
    # 四周无滑移，顶部设定一个水平速度
    # 类似经典 lid-driven cavity 问题
    # -----------------------------
    u[0, :] = 0
    u[-1, :] = 0
    u[:, 0] = 0
    u[:, -1] = 1.0

    v[0, :] = 0
    v[-1, :] = 0
    v[:, 0] = 0
    v[:, -1] = 0

# -----------------------------
# 画图
# -----------------------------
x = np.linspace(0, Lx, nx)
y = np.linspace(0, Ly, ny)
X, Y = np.meshgrid(x, y, indexing="ij")

plt.figure(figsize=(6, 6))
plt.contourf(X, Y, p, levels=30)
plt.colorbar(label="pressure")
plt.quiver(X, Y, u, v)
plt.xlabel("x")
plt.ylabel("y")
plt.title("2D incompressible flow")
plt.show()